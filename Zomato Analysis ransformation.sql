-- ------------------------------------------------------------
-- STEP 1: DATABASE INITIALIZATION
-- ------------------------------------------------------------
CREATE DATABASE IF NOT EXISTS ZomatoDB;
USE ZomatoDB;

-- ------------------------------------------------------------
-- STEP 2: SCHEMA CREATION (TABLE DEFINITIONS)
-- ------------------------------------------------------------
DROP TABLE IF EXISTS Zomato_Orders;
DROP TABLE IF EXISTS Zomato_Restaurants;

CREATE TABLE Zomato_Restaurants (
    restaurant_id VARCHAR(50) PRIMARY KEY,
    restaurant_name VARCHAR(150) NOT NULL,
    city VARCHAR(100) NOT NULL,
    area VARCHAR(100),
    cuisine VARCHAR(100),
    avg_rating DECIMAL(3, 2),
    total_ratings INT DEFAULT 0,
    price_range VARCHAR(20),
    delivery_available VARCHAR(10)
);

CREATE TABLE Zomato_Orders (
    order_id VARCHAR(50) PRIMARY KEY,
    restaurant_id VARCHAR(50),
    customer_id VARCHAR(50),
    order_date DATE,
    order_time TIME,
    delivery_time INT,
    total_cost DECIMAL(10, 2),
    item_count INT,
    payment_method VARCHAR(50),
    customer_rating DECIMAL(3, 2),
    FOREIGN KEY (restaurant_id) REFERENCES Zomato_Restaurants(restaurant_id) ON DELETE SET NULL
);

-- ------------------------------------------------------------
-- TASK 2.1: BASIC DATA CLEANING
-- ------------------------------------------------------------

-- Remove Duplicates from Zomato_Restaurants (if any)
CREATE TABLE Zomato_Restaurants_Clean AS
SELECT DISTINCT * FROM Zomato_Restaurants;

DROP TABLE Zomato_Restaurants;
RENAME TABLE Zomato_Restaurants_Clean TO Zomato_Restaurants;
ALTER TABLE Zomato_Restaurants ADD PRIMARY KEY (restaurant_id);

-- Remove Duplicates from Zomato_Orders (if any)
CREATE TABLE Zomato_Orders_Clean AS
SELECT DISTINCT * FROM Zomato_Orders;

DROP TABLE Zomato_Orders;
RENAME TABLE Zomato_Orders_Clean TO Zomato_Orders;
ALTER TABLE Zomato_Orders ADD PRIMARY KEY (order_id);

-- Handle NULL Values in Zomato_Restaurants
UPDATE Zomato_Restaurants
SET avg_rating = COALESCE(avg_rating, 0),
    total_ratings = COALESCE(total_ratings, 0),
    cuisine = COALESCE(cuisine, 'Unknown/Not Specified'),
    area = COALESCE(area, 'Unknown Area');

-- Handle NULL Values in Zomato_Orders
UPDATE Zomato_Orders
SET delivery_time = COALESCE(delivery_time, 0),
    total_cost = COALESCE(total_cost, 0.00),
    customer_rating = COALESCE(customer_rating, 0);

-- ------------------------------------------------------------
-- TASK 2.2: DATA EXPLORATION QUERIES
-- ------------------------------------------------------------

-- Query 1: Count the number of restaurants in each city
SELECT 
    city, 
    COUNT(restaurant_id) AS total_restaurants
FROM Zomato_Restaurants
GROUP BY city
ORDER BY total_restaurants DESC;

-- Query 2: Find the top 5 cities with the highest number of orders
SELECT 
    r.city, 
    COUNT(o.order_id) AS total_orders
FROM Zomato_Orders o
JOIN Zomato_Restaurants r ON o.restaurant_id = r.restaurant_id
GROUP BY r.city
ORDER BY total_orders DESC
LIMIT 5;

-- Query 3: Calculate total revenue generated by each restaurant
SELECT 
    r.restaurant_id, 
    r.restaurant_name, 
    r.city,
    SUM(o.total_cost) AS total_revenue
FROM Zomato_Orders o
JOIN Zomato_Restaurants r ON o.restaurant_id = r.restaurant_id
GROUP BY r.restaurant_id, r.restaurant_name, r.city
ORDER BY total_revenue DESC;

-- ------------------------------------------------------------
-- TASK 2.3: DATA AGGREGATION QUERIES
-- ------------------------------------------------------------

-- Query 1: Find average order amount for each city
SELECT 
    r.city, 
    ROUND(AVG(o.total_cost), 2) AS avg_order_amount,
    COUNT(o.order_id) AS total_orders,
    ROUND(SUM(o.total_cost), 2) AS total_city_revenue
FROM Zomato_Orders o
JOIN Zomato_Restaurants r ON o.restaurant_id = r.restaurant_id
GROUP BY r.city
ORDER BY avg_order_amount DESC;

-- Query 2: Identify the top 5 restaurants with highest total sales
SELECT 
    r.restaurant_id,
    r.restaurant_name, 
    r.city, 
    r.cuisine,
    COUNT(o.order_id) AS total_orders_count,
    ROUND(SUM(o.total_cost), 2) AS total_sales
FROM Zomato_Orders o
JOIN Zomato_Restaurants r ON o.restaurant_id = r.restaurant_id
GROUP BY r.restaurant_id, r.restaurant_name, r.city, r.cuisine
ORDER BY total_sales DESC
LIMIT 5;

-- ------------------------------------------------------------
-- TASK 2.4: DATA JOINS & REPORTING
-- ------------------------------------------------------------

-- Full Order Details Join (Used for Power BI Import)
CREATE OR REPLACE VIEW Zomato_Transformed_View AS
SELECT 
    o.order_id,
    o.customer_id,
    o.order_date,
    o.order_time,
    o.delivery_time,
    o.total_cost AS order_amount,
    o.item_count,
    o.payment_method,
    o.customer_rating AS order_rating,
    r.restaurant_id,
    r.restaurant_name,
    r.city,
    r.area,
    r.cuisine,
    r.avg_rating AS restaurant_avg_rating,
    r.total_ratings AS restaurant_total_ratings,
    r.price_range,
    r.delivery_available
FROM Zomato_Orders o
INNER JOIN Zomato_Restaurants r ON o.restaurant_id = r.restaurant_id;

-- SELECT from View to confirm
SELECT * FROM Zomato_Transformed_View LIMIT 100;
